# list
# empty list
data = []
print(data)

data = [21,22,23,24,25,26]
print(data)

# access item from list

print(data[3])

print(data[1:4])

# update data
data[3] = 55
print(data)

# add new data

data.append(100)
print(data)

# add more data
data.extend([1,2,3])
print(data)

# add data by index

data.insert(2,"java")
print(data)

# delete
data.remove(22)
print(data)














