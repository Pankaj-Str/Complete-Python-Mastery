# Arithmetic Operators
x = 987
y = 67

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x // y)
print(x ** 3)
print(x % y)

# Comparison Operators
print(34 == 134)
print(34 != 134)

print(34 < 134)
print(34 > 134)

print(34 <= 34)

print(34 >= 134)

# Assignment Operators

a = 23
print(a)
# a = a + 10
a += 10
print(a)

# Logical Operators
# and 
print(45 < 67 and 67 != 67)
# or
print(45 < 67 or 67 != 67)
# not
print(not 34 == 34)
print(34 != 34)


# Membership Operators

data = "codeswithpankaj"

print("w" in data)
print("w" not in data)

# Identity Operators
data1 = "cwpc"
data2 = "codeswithpankaj"

print(data1 is data2)

print(data1 is not data2)











