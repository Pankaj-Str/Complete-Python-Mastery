# Arithmetic Operators

x = 123
y = 9
print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x // y)
print(x % y)
print(x ** 5)


# Comparison Operators (Checking Things)

print(23 == 34)
print(23 != 45)
print(45 < 67)
print(34 > 16)
print(30 <= 67)
print(34 >= 15)


# Logical Operators
# and
print(45 < 90 and 67 != 67)
# or
print(45 < 90 or 67 != 67)
# not
print(not 34 == 34)

# Membership Operators
# in
data = "CWPC"
print('C' in data)
# not in
print('z' not in data)

x1 = "CWPC"
x2 = "CWP"
# is
print(x1 is x2)
# is not
print(x1 is not x2)






















